@dataclass(frozen=True)
class PnlSeriesSpec:
    key: str
    label: str
    color: str
    dash: Optional[str] = None


# Base set (scripts/run.py "Agent PnL" panel). We'll filter this list based on config.
BASE_PNL_SPECS: Tuple[PnlSeriesSpec, ...] = (
    PnlSeriesSpec("smart_router_pnl_cum", "Smart router PnL", "#1f77b4", None),
    PnlSeriesSpec("noise_trader_pnl_cum", "Noise trader PnL", "#ff7f0e", "dash"),
    PnlSeriesSpec("arb_pnl_cum", "Arbitrageur PnL", "#2ca02c", None),
    PnlSeriesSpec("lp_pnl_active", "Active LP hedged", "#9467bd", "dash"),
    PnlSeriesSpec("jiter_pnl_series", "Jiter hedged", "#d62728", None),
    PnlSeriesSpec("lp_pnl_passive", "Passive LP hedged", "#8c564b", "dot"),
)


def _slice_series(values: Sequence[float], skip: int) -> np.ndarray:
    arr = np.asarray(values, dtype=float)
    if arr.size == 0:
        return arr
    s0 = max(0, min(int(skip), int(arr.size)))
    return arr[s0:]


def _slice_sr_dex_share(values: Sequence[float], steps: Sequence[int], skip: int) -> np.ndarray:
    arr = np.asarray(values, dtype=float)
    if arr.size == 0 or int(skip) <= 0:
        return arr
    steps_arr = np.asarray(steps, dtype=int)
    if steps_arr.size != arr.size:
        # Fallback: keep all values if step alignment is unclear.
        return arr
    return arr[steps_arr >= int(skip)]


def _concat_series(results: Sequence[Dict[str, Any]], key: str) -> np.ndarray:
    series = [
        r[key]
        for r in results
        if isinstance(r.get(key), np.ndarray) and r[key].size > 0
    ]
    if not series:
        return np.array([], dtype=float)
    return np.concatenate(series, axis=0)


def _add_quartile_legend_traces(
    fig: go.Figure,
    *,
    values: np.ndarray,
    label_prefix: str,
    color: str,
    row: int,
    col: int,
) -> None:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return
    q1, q2, q3 = np.percentile(arr, [25.0, 50.0, 75.0])
    styles = [
        ("Q1", q1, "dash"),
        ("Median", q2, None),
        ("Q3", q3, "dot"),
    ]
    for label, value, dash in styles:
        line = dict(color=color, width=2)
        if dash:
            line["dash"] = dash
        fig.add_trace(
            go.Scatter(
            x=[0, 1],
            y=[0, 1],
            mode="lines",
            line=line,
            name=f"{label_prefix} {label} = {value:.6g}",
            hoverinfo="skip",
            visible="legendonly",
            showlegend=True,
            ),
            row=row,
            col=col,
        )
        fig.update_layout(
            legend=dict(font=dict(size=18, color="black")),
            font=dict(size=18, color="black")
        )


def _hex_to_rgb(hex_color: str) -> Tuple[int, int, int]:
    s = str(hex_color).strip()
    if s.startswith("#"):
        s = s[1:]
    if len(s) != 6:
        raise ValueError(f"Expected #RRGGBB hex color, got {hex_color!r}")
    r = int(s[0:2], 16)
    g = int(s[2:4], 16)
    b = int(s[4:6], 16)
    return r, g, b


def _add_mean_std_band(
    fig: go.Figure,
    *,
    x: np.ndarray,
    mean: np.ndarray,
    std: np.ndarray,
    name: str,
    color: str,
    dash: Optional[str],
    band_alpha: float = 0.18,
) -> None:
    lower = mean - std
    upper = mean + std

    r, g, b = _hex_to_rgb(color)
    fill = f"rgba({r},{g},{b},{band_alpha})"

    # Lower bound (invisible legend)
    fig.add_trace(
        go.Scatter(
            x=x,
            y=lower,
            mode="lines",
            line=dict(width=0),
            showlegend=False,
            hoverinfo="skip",
        )
    )
    # Upper bound, filled down to lower
    fig.add_trace(
        go.Scatter(
            x=x,
            y=upper,
            mode="lines",
            line=dict(width=0),
            fill="tonexty",
            fillcolor=fill,
            showlegend=False,
            hoverinfo="skip",
            name=f"{name} ±1σ",
        )
    )

    line = dict(width=2, color=color)
    if dash:
        line["dash"] = dash

    # Mean line (legend entry)
    fig.add_trace(
        go.Scatter(
            x=x,
            y=mean,
            mode="lines",
            name=f"{name}",
            line=line,
        )
    )

    fig.update_layout(
    legend=dict(
        font=dict(size=18),
        itemsizing="constant",  # prevents shrinking with many traces
        itemwidth=50            # horizontal spacing for each item
    )
)


def _resolve_pnl_specs(params: Dict[str, Any]) -> List[PnlSeriesSpec]:
    """Filter BASE_PNL_SPECS based on which agent cohorts exist in this scenario."""
    try:
        # Accept both spellings to match different configs.
        passive_share = float(params.get("passive_lp_share", params.get("lp_passive_share", 1.0)))
    except (TypeError, ValueError):
        passive_share = 1.0
    passive_share = max(0.0, min(1.0, passive_share))

    try:
        smart_raw = params.get("smart_trades_per_second", None)
        if smart_raw is None:
            smart_raw = params.get("smart_trades_per_block", 0.0)
        smart_trades = float(smart_raw)
    except (TypeError, ValueError):
        smart_trades = 0.0
    try:
        noise_raw = params.get("noise_trades_per_second", None)
        if noise_raw is None:
            noise_raw = params.get("noise_trades_per_block", 0.0)
        noise_trades = float(noise_raw)
    except (TypeError, ValueError):
        noise_trades = 0.0

    # JIT enabled iff all three are strictly positive.
    try:
        p_jit = float(params.get("p_jit", 0.0))
    except (TypeError, ValueError):
        p_jit = 0.0
    try:
        n_jit = int(params.get("N_jit", 0))
    except (TypeError, ValueError):
        n_jit = 0
    try:
        liq_perc = float(params.get("liquidity_perc_jit", 0.0))
    except (TypeError, ValueError):
        liq_perc = 0.0

    include_active = passive_share < 1.0
    include_passive = passive_share > 0.0
    include_jit = p_jit > 0.0 and n_jit > 0 and liq_perc > 0.0
    # Only plot cohorts that actually generate trades/PnL in this scenario.
    include_smart_router = smart_trades > 0.0
    include_noise_trader = noise_trades > 0.0

    specs: List[PnlSeriesSpec] = []
    for spec in BASE_PNL_SPECS:
        if spec.key == "lp_pnl_active" and not include_active:
            continue
        if spec.key == "lp_pnl_passive" and not include_passive:
            continue
        if spec.key == "jiter_pnl_series" and not include_jit:
            continue
        if spec.key == "smart_router_pnl_cum" and not include_smart_router:
            continue
        if spec.key == "noise_trader_pnl_cum" and not include_noise_trader:
            continue
        specs.append(spec)
    return specs


def _run_one_seed(
    seed: int,
    *,
    base_params: Dict[str, Any],
    tmp_root: Path,
    keep_run_artifacts: bool,
) -> Dict[str, Any]:
    """Worker function. Returns sliced PnL series for this seed."""
    # Import inside worker to avoid any weird cross-process global state.
    from scripts import run as _run_module

    _run_module.tqdm = _silent_tqdm  # type: ignore[attr-defined]

    params = dict(base_params)
    # Pop internal key before calling simulate (it doesn't accept it).
    pnl_keys = params.pop("_pnl_keys", [])
    extra_series_keys = params.pop("_extra_series_keys", [])
    params["seed"] = int(seed)

    run_dir = tmp_root / f"seed_{int(seed)}"
    run_dir.mkdir(parents=True, exist_ok=True)
    params["results_root"] = run_dir

    out = _run_module.simulate(**params)

    # Slice series after skip_step (same idea as scripts/run.py visualization skip)
    skip_step = int(params.get("skip_step", 0))

    payload: Dict[str, Any] = {"seed": int(seed)}
    for key in pnl_keys:
        payload[key] = _slice_series(out.get(key, []), skip_step)

    for key in extra_series_keys:
        if key == "fee_series":
            payload[key] = _slice_series(out.get(key, []), skip_step)
        elif key == "smart_router_dex_share_series":
            payload[key] = _slice_sr_dex_share(
                out.get("smart_router_dex_share_series", []),
                out.get("smart_router_dex_share_steps", []),
                skip_step,
            )

    def _sum_counts(values: Any) -> int:
        if isinstance(values, (list, tuple, np.ndarray)):
            return int(np.sum(values))
        return 0

    smart_cex = int(
        out.get("smart_router_swaps_cex_routed", _sum_counts(out.get("smart_router_cex_exec_count", [])))
    )
    smart_dex = int(
        out.get("smart_router_swaps_dex_routed", _sum_counts(out.get("smart_router_dex_exec_count", [])))
    )
    smart_total = out.get("total_smart_router_swaps")
    if smart_total is None:
        smart_total = smart_cex + smart_dex
        if smart_total == 0:
            smart_total = _sum_counts(out.get("smart_router_exec_count", []))

    payload["total_smart_router_swaps"] = int(smart_total)
    payload["smart_router_swaps_cex_routed"] = int(smart_cex)
    payload["smart_router_swaps_dex_routed"] = int(smart_dex)
    payload["smart_router_swaps_rejected_slippage"] = int(out.get("smart_router_swaps_rejected_slippage", 0))

    payload["total_noise_trader_swaps"] = int(
        out.get("total_noise_trader_swaps", _sum_counts(out.get("noise_trader_exec_count", [])))
    )
    payload["noise_trader_swaps_rejected_slippage"] = int(out.get("noise_trader_swaps_rejected_slippage", 0))

    payload["total_arb_swaps"] = int(out.get("total_arb_swaps", _sum_counts(out.get("arb_exec_count", []))))
    payload["arb_no_op_in_band"] = int(out.get("arb_no_op_in_band", 0))
    payload["arb_swaps_rejected_profitability"] = int(out.get("arb_swaps_rejected_profitability", 0))
    payload["total_jit_trades_executed"] = int(out.get("total_jit_trades_executed", 0))

    if not keep_run_artifacts:
        shutil.rmtree(run_dir, ignore_errors=True)

    return payload


def parse_args() -> argparse.Namespace:
    """Parse CLI arguments for multi-run simulations.

    Parameters:
        None.

    Returns:
        argparse.Namespace: Parsed CLI options for run_multiple.

    Notes:
        Reads from sys.argv and applies default values defined in this module.

    Examples:
        >>> args = parse_args()
    """
    valid_fee_modes = ("static", "toxicity", "volatility_cex", "volatility_dex")
    p = argparse.ArgumentParser(description="Run N seeds and plot mean±std PnL bands.")
    p.add_argument("--config", required=True, type=Path, help="Path to the YAML scenario config. Required.")
    p.add_argument("--runs", type=int, default=10, help="Number of runs/seeds. Default is 10.")
    p.add_argument(
        "--seed-base",
        type=int,
        default=None,
        help="Base seed (defaults to the YAML seed). Seeds are seed_base + i*seed_step.",
    )
    p.add_argument("--seed-step", type=int, default=1, help="Seed increment per run.")
    p.add_argument(
        "--max-workers",
        type=int,
        default=max(1, (os.cpu_count() or 1) - 1),
        help="Number of parallel worker processes. Defaults to number of CPUs minus one.",
    )
    p.add_argument(
        "--keep-run-artifacts",
        action="store_true",
        help=(
            "Keep per-run temp folders/logs under multi_runs/_tmp_runs/<pid>/... "
            "Default is to delete them."
        ),
    )
    p.add_argument(
        "--band-sigma-mult",
        type=float,
        default=2.0,
        help="Shaded band = ±mult*std. Default 2.0 (±2σ).",
    )
    p.add_argument(
        "--fee-modes",
        nargs="+",
        default=list(valid_fee_modes),
        choices=list(valid_fee_modes),
        help=(
            "Fee modes to run. Provide one or more values. "
            "Default runs all supported modes."
        ),
    )
    return p.parse_args()


def main() -> None:
    """Run multi-seed simulations and write aggregated outputs.

    Parameters:
        None.

    Returns:
        None.

    Notes:
        Writes plots and a trade-summary log under the scenario's multi_runs folder.

    Examples:
        >>> main()
    """
    args = parse_args()

    if args.runs <= 0:
        raise SystemExit("--runs must be positive.")
    if args.seed_step <= 0:
        raise SystemExit("--seed-step must be positive.")
    if args.max_workers <= 0:
        raise SystemExit("--max-workers must be positive.")

    print("PID:", os.getpid())
    config_path = args.config.expanduser().resolve()

    _, base_params = load_simulation_parameters(config_path, simulate_func=simulate)
    base_params = dict(base_params)

    fee_modes = [str(mode).lower() for mode in args.fee_modes]

    scenario_root = scenario_output_root(config_path)
    out_root = scenario_root / "multi_runs"
    out_root.mkdir(parents=True, exist_ok=True)

    # Stable invocation id (deterministic base; uniqueness handled via suffix).
    seed0 = int(args.seed_base) if args.seed_base is not None else int(base_params.get("seed", 1))
    invocation_id_base = safe_tag(
        f"{config_path.stem}_runs{int(args.runs)}_seed{seed0}_step{int(args.seed_step)}"
    )
    invocation_root = make_unique_dir(out_root / invocation_id_base)

    snapshot_file(config_path, invocation_root / "config_snapshot.yml")
    manifest = build_run_manifest(script="run_multiple", run_id=invocation_root.name, config_path=config_path)
    write_json(
        invocation_root / "metadata.json",
        {
            **manifest.to_dict(),
            "fee_modes": list(fee_modes),
            "runs": int(args.runs),
            "seed_base": int(seed0),
            "seed_step": int(args.seed_step),
            "max_workers": int(args.max_workers),
            "config_stem": str(config_path.stem),
        },
    )

    # Use a per-invocation temp root to avoid collisions across concurrent runs.
    run_tmp_root = make_unique_dir(invocation_root / "_tmp_runs")

    base_params_common = dict(base_params)
    # We need PnL series => light_mode must be False.
    base_params_common["light_mode"] = False
    # Avoid per-run plots; we only want the aggregated plot.
    base_params_common["visualize"] = False
    # Reduce stdout; note: scripts/run.py still writes a verbose log file unless light_mode=True.
    base_params_common["verbose"] = False

    summary_rows: List[Dict[str, Any]] = []

    for fee_mode in fee_modes:
        print(f"[multi_runs] Generating runs for fee_mode={fee_mode}...")
        mode_root = invocation_root / safe_tag(fee_mode)
        png_dir = mode_root / "png"
        html_dir = mode_root / "html"
        png_dir.mkdir(parents=True, exist_ok=True)
        html_dir.mkdir(parents=True, exist_ok=True)

        params = dict(base_params_common)
        params["fee_mode"] = str(fee_mode)

        # Decide which PnL series to include.
        pnl_specs = _resolve_pnl_specs(params)
        pnl_keys = [spec.key for spec in pnl_specs]
        if not pnl_keys:
            raise SystemExit("No PnL series selected; check your config.")

        # Stash keys into params so worker can avoid pickling specs objects.
        params["_pnl_keys"] = pnl_keys
        params["_extra_series_keys"] = ["fee_series", "smart_router_dex_share_series"]

        skip_step = int(params.get("skip_step", 0))
        seeds = [int(seed0 + i * int(args.seed_step)) for i in range(int(args.runs))]

        # Separate fee modes within the same invocation to avoid overwriting artifacts
        # when --keep-run-artifacts is enabled.
        tmp_root = run_tmp_root / safe_tag(str(fee_mode))
        tmp_root.mkdir(parents=True, exist_ok=True)

        # --- parallel execution -------------------------------------------------
        from concurrent.futures import ProcessPoolExecutor, as_completed
        from tqdm import tqdm

        results: List[Dict[str, Any]] = []
        with ProcessPoolExecutor(max_workers=int(args.max_workers)) as executor:
            futures = [
                executor.submit(
                    _run_one_seed,
                    seed,
                    base_params=params,
                    tmp_root=tmp_root,
                    keep_run_artifacts=bool(args.keep_run_artifacts),
                )
                for seed in seeds
            ]

            with tqdm(total=len(futures), desc="Seeds", unit="run") as pbar:
                for fut in as_completed(futures):
                    results.append(fut.result())
                    pbar.update(1)

        # Reorder results by seed for consistent output.
        results.sort(key=lambda r: int(r.get("seed", 0)))

        total_smart_router_swaps = sum(int(r.get("total_smart_router_swaps", 0)) for r in results)
        total_smart_router_swaps_cex = sum(int(r.get("smart_router_swaps_cex_routed", 0)) for r in results)
        total_smart_router_swaps_dex = sum(int(r.get("smart_router_swaps_dex_routed", 0)) for r in results)
        total_smart_router_rejected = sum(
            int(r.get("smart_router_swaps_rejected_slippage", 0)) for r in results
        )

        total_noise_trader_swaps = sum(int(r.get("total_noise_trader_swaps", 0)) for r in results)
        total_noise_trader_rejected = sum(
            int(r.get("noise_trader_swaps_rejected_slippage", 0)) for r in results
        )

        total_arb_swaps = sum(int(r.get("total_arb_swaps", 0)) for r in results)
        total_arb_no_op = sum(int(r.get("arb_no_op_in_band", 0)) for r in results)
        total_arb_rejected_profitability = sum(
            int(r.get("arb_swaps_rejected_profitability", 0)) for r in results
        )
        total_jit_trades_executed = sum(int(r.get("total_jit_trades_executed", 0)) for r in results)
        n_runs = max(1, len(results))

        smart_total_arr = np.array(
            [int(r.get("total_smart_router_swaps", 0)) for r in results], dtype=float
        )
        smart_cex_arr = np.array(
            [int(r.get("smart_router_swaps_cex_routed", 0)) for r in results], dtype=float
        )
        smart_dex_arr = np.array(
            [int(r.get("smart_router_swaps_dex_routed", 0)) for r in results], dtype=float
        )
        smart_rejected_arr = np.array(
            [int(r.get("smart_router_swaps_rejected_slippage", 0)) for r in results], dtype=float
        )

        noise_total_arr = np.array(
            [int(r.get("total_noise_trader_swaps", 0)) for r in results], dtype=float
        )
        noise_rejected_arr = np.array(
            [int(r.get("noise_trader_swaps_rejected_slippage", 0)) for r in results], dtype=float
        )

        arb_total_arr = np.array(
            [int(r.get("total_arb_swaps", 0)) for r in results], dtype=float
        )
        arb_no_op_arr = np.array(
            [int(r.get("arb_no_op_in_band", 0)) for r in results], dtype=float
        )
        arb_rejected_arr = np.array(
            [int(r.get("arb_swaps_rejected_profitability", 0)) for r in results], dtype=float
        )

        jit_executed_arr = np.array(
            [int(r.get("total_jit_trades_executed", 0)) for r in results], dtype=float
        )

        smart_total_mean = float(np.mean(smart_total_arr)) if n_runs > 0 else float("nan")
        smart_total_std = float(np.std(smart_total_arr)) if n_runs > 0 else float("nan")
        smart_cex_mean = float(np.mean(smart_cex_arr)) if n_runs > 0 else float("nan")
        smart_cex_std = float(np.std(smart_cex_arr)) if n_runs > 0 else float("nan")
        smart_dex_mean = float(np.mean(smart_dex_arr)) if n_runs > 0 else float("nan")
        smart_dex_std = float(np.std(smart_dex_arr)) if n_runs > 0 else float("nan")
        smart_rejected_mean = float(np.mean(smart_rejected_arr)) if n_runs > 0 else float("nan")
        smart_rejected_std = float(np.std(smart_rejected_arr)) if n_runs > 0 else float("nan")

        noise_total_mean = float(np.mean(noise_total_arr)) if n_runs > 0 else float("nan")
        noise_total_std = float(np.std(noise_total_arr)) if n_runs > 0 else float("nan")
        noise_rejected_mean = float(np.mean(noise_rejected_arr)) if n_runs > 0 else float("nan")
        noise_rejected_std = float(np.std(noise_rejected_arr)) if n_runs > 0 else float("nan")

        arb_total_mean = float(np.mean(arb_total_arr)) if n_runs > 0 else float("nan")
        arb_total_std = float(np.std(arb_total_arr)) if n_runs > 0 else float("nan")
        arb_no_op_mean = float(np.mean(arb_no_op_arr)) if n_runs > 0 else float("nan")
        arb_no_op_std = float(np.std(arb_no_op_arr)) if n_runs > 0 else float("nan")
        arb_rejected_mean = float(np.mean(arb_rejected_arr)) if n_runs > 0 else float("nan")
