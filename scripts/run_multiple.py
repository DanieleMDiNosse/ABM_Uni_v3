#!/usr/bin/env python3
"""scripts/run_multiple.py

Run the ABM simulation N times with different seeds and plot mean ± std bands
for the PnL time series (similar to the PnL panel generated by scripts/run.py).

Implements:
- (a) Parallel execution across seeds.
- (b) Auto-include only the agent PnL series that are meaningful for the scenario
      (e.g., hide active LP series when passive_lp_share=1, hide JIT series when
      JIT is disabled, hide smart/noise routers when their trades_per_block are 0).

Outputs:
  abm_results/scenarios/<scenario>/multi_runs/<run_id>/<fee_mode>/{html,png}/
  abm_results/scenarios/<scenario>/multi_runs/<run_id>/summary.csv
  abm_results/scenarios/<scenario>/multi_runs/<run_id>/metadata.json

Example:
  python -m scripts.run_multiple --config configs/scenarios/section4_microstructure_model0_static.yml --runs 20 --seed-base 1 --max-workers 8

Notes:
- We call scripts.run.simulate() directly (instead of spawning `python -m scripts.run`) so that we
  can collect the PnL series in-memory.
- `verbose=False` does not disable scripts/run.py's per-run verbose log file (it is
  controlled by light_mode). To avoid clutter, we route each worker's outputs to
  a per-seed temp folder (scoped under a per-invocation PID folder) and delete
  them by default.
"""

