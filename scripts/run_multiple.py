def _silent_tqdm(iterable=None, **kwargs):
    """Silence tqdm inside scripts.run.simulate to avoid nested progress bars."""
    if iterable is None:
        total = int(kwargs.get("total", 0))
        return range(total)
    return iterable


# Monkeypatch tqdm used inside scripts/run.py
